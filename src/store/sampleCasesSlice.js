import { createSlice } from '@reduxjs/toolkit';
import { SAMPLE_CASES } from '../utils/incidentStorage';

// Initial state for the sample cases feature
const initialState = {
  cases: SAMPLE_CASES,
  selectedSample: SAMPLE_CASES[0] || null,
};

// Redux Toolkit slice: combines actions and reducers in one definition
export const sampleCasesSlice = createSlice({
  name: 'sampleCases',
  initialState,
  reducers: {
    // Action to update the currently selected sample scenario
    selectSample: (state, action) => {
      // Redux Toolkit uses Immer internally for safe mutable updates
      state.selectedSample = action.payload;
    },
    // Action to reset the selection back to the first available sample
    resetSampleSelection: (state) => {
      state.selectedSample = state.cases[0] || null;
    },
  },
});

// Action creators automatically generated by createSlice
export const { selectSample, resetSampleSelection } = sampleCasesSlice.actions;

// Reducer to be registered in the central Redux store
export default sampleCasesSlice.reducer;
